CREATE TABLE IF NOT EXISTS myapp_catalog_filter_aggregate (
    SECTION_ID INT NOT NULL,
    CONFIG_HASH VARCHAR(32) NOT NULL,
    PAYLOAD_JSON LONGTEXT NOT NULL,
    IS_STALE CHAR(1) NOT NULL DEFAULT 'N',
    UPDATED_AT DATETIME NOT NULL,
    LAST_ERROR TEXT NULL,
    PRIMARY KEY (SECTION_ID),
    INDEX ix_myapp_filter_agg_stale (IS_STALE)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_rebuild_queue (
    SECTION_ID INT NOT NULL,
    JOB_ID INT NOT NULL DEFAULT 0,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (SECTION_ID),
    INDEX ix_myapp_filter_queue_job (JOB_ID)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_rebuild_job (
    ID INT NOT NULL AUTO_INCREMENT,
    TYPE VARCHAR(32) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    TOTAL INT NOT NULL DEFAULT 0,
    PROCESSED INT NOT NULL DEFAULT 0,
    ERROR_COUNT INT NOT NULL DEFAULT 0,
    CURRENT_SECTION_ID INT NOT NULL DEFAULT 0,
    PARAMS_JSON TEXT NULL,
    LAST_ERROR TEXT NULL,
    STARTED_AT DATETIME NULL,
    FINISHED_AT DATETIME NULL,
    CREATED_AT DATETIME NOT NULL,
    PRIMARY KEY (ID),
    INDEX ix_myapp_filter_job_status (STATUS)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_product (
    PRODUCT_ID INT NOT NULL,
    IBLOCK_ID INT NOT NULL,
    ACTIVE CHAR(1) NOT NULL DEFAULT 'Y',
    SORT INT NOT NULL DEFAULT 500,
    UPDATED_AT DATETIME NOT NULL,
    LAST_ERROR TEXT NULL,
    PRIMARY KEY (PRODUCT_ID),
    INDEX ix_myapp_fp_active_iblock (ACTIVE, IBLOCK_ID)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_product_section (
    PRODUCT_ID INT NOT NULL,
    SECTION_ID INT NOT NULL,
    PRIMARY KEY (PRODUCT_ID, SECTION_ID),
    INDEX ix_myapp_fps_section_product (SECTION_ID, PRODUCT_ID)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_value (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    PRODUCT_ID INT NOT NULL,
    PROPERTY_ID INT NOT NULL,
    VALUE_ENUM INT NULL,
    VALUE_NUM DECIMAL(18,4) NULL,
    VALUE_STR VARCHAR(500) NULL,
    PRIMARY KEY (ID),
    INDEX ix_myapp_fv_prop_enum (PROPERTY_ID, VALUE_ENUM, PRODUCT_ID),
    INDEX ix_myapp_fv_prop_num (PROPERTY_ID, VALUE_NUM, PRODUCT_ID),
    INDEX ix_myapp_fv_product_prop (PRODUCT_ID, PROPERTY_ID)
);

CREATE TABLE IF NOT EXISTS myapp_catalog_filter_index_meta (
    ID INT NOT NULL DEFAULT 1,
    INDEX_VERSION INT NOT NULL DEFAULT 0,
    CONFIG_HASH VARCHAR(32) NOT NULL DEFAULT '',
    PRODUCTS_COUNT INT NOT NULL DEFAULT 0,
    VALUES_COUNT INT NOT NULL DEFAULT 0,
    LAST_FULL_SYNC_AT DATETIME NULL,
    LAST_ERROR TEXT NULL,
    PRIMARY KEY (ID)
);

